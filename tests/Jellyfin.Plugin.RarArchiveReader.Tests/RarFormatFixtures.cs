using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using Microsoft.Extensions.Logging.Abstractions;

namespace Jellyfin.Plugin.RarArchiveReader.Tests
{
    /// <summary>
    /// Describes one archive fixture and what the plugin is expected to do with it.
    /// </summary>
    /// <param name="Name">Fixture directory name.</param>
    /// <param name="FirstVolume">File name of the volume the plugin should open.</param>
    /// <param name="Compressed">True when entries are compressed (no direct stored access).</param>
    /// <param name="VolumeCount">Number of volume files on disk.</param>
    /// <param name="SupportedBySharpCompress">
    /// False for formats the bundled SharpCompress cannot read. Kept explicit so a future
    /// library upgrade that adds support turns into a visible test failure rather than
    /// silently changing behaviour.
    /// </param>
    public sealed record RarFixture(
        string Name,
        string FirstVolume,
        bool Compressed,
        int VolumeCount,
        bool SupportedBySharpCompress = true)
    {
        public string Directory => Path.Combine(RarFormatFixtures.ArchiveRoot, Name);

        public string FirstVolumePath => Path.Combine(Directory, FirstVolume);

        public override string ToString() => Name;
    }

    /// <summary>
    /// Locates the committed fixture archives and the payload files they were built from.
    /// Fixtures are generated by <c>tests/fixtures/generate-fixtures.sh</c>.
    /// </summary>
    public static class RarFormatFixtures
    {
        public const string PayloadEntry = "payload.bin";
        public const string NoiseEntry = "noise.bin";

        private static readonly Lazy<string> _root = new(FindFixtureRoot);

        public static string Root => _root.Value;

        public static string ArchiveRoot => Path.Combine(Root, "archives");

        public static string SourceRoot => Path.Combine(Root, "source");

        /// <summary>
        /// Every generated format. Expectations here are the regression contract:
        /// changing one should be a deliberate act, not a side effect.
        /// </summary>
        public static readonly RarFixture[] All =
        {
            new("rar4-store-single", "rar4-store-single.rar", Compressed: false, VolumeCount: 1),
            new("rar4-store-multi", "rar4-store-multi.part1.rar", Compressed: false, VolumeCount: 7),
            new("rar4-store-oldvol", "rar4-store-oldvol.rar", Compressed: false, VolumeCount: 7),
            new("rar4-comp-multi", "rar4-comp-multi.part1.rar", Compressed: true, VolumeCount: 2),
            new("rar5-store-multi", "rar5-store-multi.part1.rar", Compressed: false, VolumeCount: 7),
            new("rar5-comp-single", "rar5-comp-single.rar", Compressed: true, VolumeCount: 1),
            new("rar5-comp-multi", "rar5-comp-multi.part1.rar", Compressed: true, VolumeCount: 2),

            // Mirrors real-world releases seen in the wild that report Method v6:*:m3.
            // Proves such archives are readable, so failures on them indicate damaged
            // files rather than a missing RAR5 capability.
            new("rar5-comp-m3-multi", "rar5-comp-m3-multi.part1.rar", Compressed: true, VolumeCount: 2),
        };

        public static IEnumerable<object[]> AllCases() => All.Select(f => new object[] { f });

        public static IEnumerable<object[]> StoredCases() =>
            All.Where(f => !f.Compressed).Select(f => new object[] { f });

        public static IEnumerable<object[]> CompressedCases() =>
            All.Where(f => f.Compressed).Select(f => new object[] { f });

        public static IEnumerable<object[]> ReadableCases() =>
            All.Where(f => f.SupportedBySharpCompress).Select(f => new object[] { f });

        public static byte[] SourceBytes(string entryName) =>
            File.ReadAllBytes(Path.Combine(SourceRoot, entryName));

        public static string Sha256(byte[] data) => Convert.ToHexString(SHA256.HashData(data));

        /// <summary>Creates a file system instance with a throwaway logger.</summary>
        public static RarFileSystem CreateFileSystem() => new(NullLogger.Instance);

        private static string FindFixtureRoot()
        {
            // Walk up from the test binary until tests/fixtures is found, so the tests
            // work from the IDE, `dotnet test`, and CI alike without copying 3 MB of
            // binaries into every output directory.
            var dir = new DirectoryInfo(AppContext.BaseDirectory);
            while (dir is not null)
            {
                var candidate = Path.Combine(dir.FullName, "tests", "fixtures");
                if (Directory.Exists(Path.Combine(candidate, "archives")))
                {
                    return candidate;
                }

                dir = dir.Parent;
            }

            throw new DirectoryNotFoundException(
                "Could not locate tests/fixtures. Run tests/fixtures/generate-fixtures.sh if the fixtures are missing.");
        }
    }
}
